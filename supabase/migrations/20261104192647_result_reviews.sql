begin;

-- Guest checkout sessions have auth.users IDs, so registration is never required.
create table public.result_reviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  usage_event_id uuid references public.user_feature_usage_events(id) on delete set null,
  feature_key text not null check (feature_key in (
    'sale_estimate', 'rent_estimate', 'listing_analysis', 'cadastru_lookup', 'yield_calculator', 'pdf_report'
  )),
  is_anonymous boolean not null default false,
  visitor jsonb,
  status text not null check (status in ('submitted', 'dismissed')),
  rating smallint,
  comment text check (comment is null or char_length(comment) <= 500),
  created_at timestamptz not null default now(),
  constraint result_reviews_response check (
    (status = 'submitted' and rating is not null and rating between 1 and 5)
    or (status = 'dismissed' and rating is null and comment is null)
  )
);

create index result_reviews_submitted_created_idx on public.result_reviews (created_at desc)
  where status = 'submitted';
create index result_reviews_usage_idx on public.result_reviews (usage_event_id);
create index if not exists guest_checkout_accounts_claimed_user_idx
  on public.guest_checkout_accounts (claimed_user_id) where claimed_user_id is not null;

alter table public.result_reviews enable row level security;
revoke all on public.result_reviews from public, anon, authenticated;
revoke all on sequence public.result_reviews_id_seq from public, anon, authenticated;
grant select, insert on public.result_reviews to service_role;
grant usage, select on sequence public.result_reviews_id_seq to service_role;

commit;
